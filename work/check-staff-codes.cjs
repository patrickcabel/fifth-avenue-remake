const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {StaffAuth}=require('../staff-auth.cjs'),{BackupManager}=require('../backup-manager.cjs');
const dir=fs.mkdtempSync(path.join(__dirname,'store-test-staff-codes-'));
try{
  const file=path.join(dir,'data','staff-account.json'),auth=new StaffAuth(file);
  assert.equal(auth.configured(),false);
  assert.throws(()=>auth.setupCode('Manager','123','123'),/four digits/);
  assert.throws(()=>auth.setupCode('Manager','0001','12'),/three digits/);
  const manager=auth.setupCode('Manager','0001','007');
  assert.equal(manager.code,'0001');assert.equal(manager.role,'manager');assert.ok(!('hash' in manager));
  assert.throws(()=>auth.setupCode('Other','0002','123'),/already exists/);
  const token=auth.loginCode('0001','007','manager-device');
  const session=auth.session(auth.cookie(token));assert.equal(session.code,'0001');assert.equal(session.role,'manager');
  const employee=auth.codes.create({name:'Alex',code:'0042',pin:'009',role:'staff'});
  assert.throws(()=>auth.codes.create({name:'Other',code:'0042',pin:'123',role:'staff'}),/already assigned/);
  const employeeToken=auth.loginCode('0042','009','staff-device'),employeeCookie=auth.cookie(employeeToken);
  assert.equal(auth.session(employeeCookie).role,'staff');
  auth.codes.update(employee.id,{action:'pin',pin:'003'},session);
  assert.equal(auth.session(employeeCookie),null);
  assert.throws(()=>auth.loginCode('0042','009','reset-check'),/incorrect/);
  const changed=auth.loginCode('0042','003','staff-device');
  auth.codes.update(employee.id,{action:'active',active:false},session);
  assert.equal(auth.session(auth.cookie(changed)),null);
  assert.throws(()=>auth.loginCode('0042','003','inactive-check'),/incorrect/);
  assert.throws(()=>auth.codes.update(manager.id,{action:'active',active:false},session),/own account/);
  auth.codes.update(employee.id,{action:'active',active:true},session);
  assert.ok(auth.loginCode('0042','003','reactivate-check'));
  const restarted=new StaffAuth(file);
  assert.ok(restarted.loginCode('0001','007','restart'));
  for(let n=0;n<5;n++)assert.throws(()=>restarted.loginCode('0001','999','bruteforce',1000),/incorrect/);
  assert.throws(()=>restarted.loginCode('0001','007','other-device',1001),/Too many/);
  assert.ok(restarted.loginCode('0001','007','other-device',1000+16*60000));
  const backup=new BackupManager(path.dirname(file),path.join(dir,'backups'));
  const snapshot=backup.create();assert.ok(backup.read(snapshot.name).files['staff-codes.json']);
  assert.ok(!JSON.stringify(auth.codes.list()).includes('salt'));
  const legacyFile=path.join(dir,'legacy','staff-account.json'),legacy=new StaffAuth(legacyFile);
  legacy.setup('oldmanager','old-password-12345');
  const oldToken=legacy.login('oldmanager','old-password-12345');
  assert.equal(legacy.session(legacy.cookie(oldToken)).role,'manager');
  legacy.codes.create({name:'New Manager',code:'1000',pin:'123',role:'manager'});
  assert.ok(new StaffAuth(legacyFile).login('oldmanager','old-password-12345'));
  assert.ok(new StaffAuth(legacyFile).loginCode('1000','123'));
  console.log('PASS: code/PIN length and leading zeros, unique codes, roles, reset/revocation, deactivation, persistence, attempt limits, backups and legacy manager access');
}finally{fs.rmSync(dir,{recursive:true,force:true});}
