const {ServiceStore} = require('../service-store.cjs');
const assert = require('node:assert/strict');
const fs = require('node:fs'), path = require('node:path');
const dir=fs.mkdtempSync(path.join(__dirname,'store-test-')), file=path.join(dir,'requests.json');
try {
  const store=new ServiceStore(file);
  const input={type:'order',name:'Test Guest',phone:'555-0101',mode:'Pickup',items:[{menuId:'appetizers-22',qty:2,price:1,name:'Fake price',note:'Extra napkins'}]};
  assert.throws(()=>store.create({...input,mode:'Delivery'}),/pickup/);
  assert.throws(()=>store.create({...input,items:[{name:'Soup',qty:-1,price:400}]}),/Invalid/);
  const r=store.create(input);
  const retryInput={...input,requestKey:'test-retry-0001'};
  const original=store.create(retryInput);
  assert.equal(store.create(retryInput).id,original.id);
  assert.throws(()=>store.create({...retryInput,name:'Different guest'}),/different details/);
  store.pickup.update({revision:0,paused:true});
  assert.throws(()=>store.create(input),/temporarily paused/);
  assert.equal(store.create(retryInput).id,original.id);
  assert.equal(new ServiceStore(file).pickup.get().paused,true);
  store.pickup.update({revision:1,paused:false});
  assert.throws(()=>store.pickup.update({revision:0,paused:true}),/changed/);
  assert.equal(r.items[0].price,400);
  assert.equal(r.items[0].name,'Miso Soup');
  assert.equal(r.items[0].note,'Extra napkins');
  assert.equal(r.subtotal,800);
  assert.throws(()=>store.create({...input,items:[{menuId:'missing',qty:1}]}),/sold out/);
  assert.throws(()=>store.create({...input,items:[{menuId:'appetizers-22',qty:1.5}]}),/Invalid/);
  assert.equal(r.status,'pending');
  assert.throws(()=>store.update(r.id,{revision:1,action:'complete'}),/not available/);
  const timed=store.update(r.id,{revision:1,action:'time',minutes:45});
  assert.throws(()=>store.update(r.id,{revision:1,action:'accept'}),/Another staff/);
  const accepted=store.update(r.id,{revision:timed.revision,action:'accept'});
  assert.equal(accepted.readyAt-accepted.acceptedAt,45*60000);
  const ready=store.update(r.id,{revision:accepted.revision,action:'ready'});
  const collected=store.update(r.id,{revision:ready.revision,action:'complete'});
  assert.equal(collected.status,'completed');
  const reopened=new ServiceStore(file);
  assert.equal(reopened.list().find(i=>i.id===r.id).status,'completed');
  assert.equal(reopened.list().find(i=>i.id===r.id).events.length,5);
  const futureDate=new Date(Date.now()+7*86400000).toISOString().slice(0,10);
  const reservationInput={type:'reservation',name:'Test Guest',phone:'555-0102',guests:4,date:futureDate,time:'19:00'};
  const reservation=store.create(reservationInput);
  assert.throws(()=>store.update(reservation.id,{revision:1,action:'decline',reason:' '}),/reason/);
  assert.equal(store.update(reservation.id,{revision:1,action:'accept'}).status,'confirmed');
  const staffInput={...reservationInput,source:'staff',confirmed:true,requestKey:'staff-reservation-test'};
  const staffReservation=store.create(staffInput);
  assert.equal(staffReservation.source,'staff');
  assert.equal(staffReservation.status,'confirmed');
  assert.equal(staffReservation.events[1].action,'accept');
  assert.equal(store.create(staffInput).id,staffReservation.id);
  assert.throws(()=>store.create({...staffInput,confirmed:false}),/different details/);
  assert.throws(()=>store.create({...reservationInput,date:'2000-01-01'}),/future/);
  assert.throws(()=>store.create({...reservationInput,date:'2099-02-30'}),/calendar/);
  assert.throws(()=>store.create({...reservationInput,time:'25:00'}),/valid reservation/);
  assert.throws(()=>store.create({...reservationInput,guests:0}),/Party size/);
  assert.throws(()=>store.create({...reservationInput,confirmed:true}),/Only staff/);
  store.pickup.update({revision:2,paused:true});
  assert.equal(store.create({...reservationInput,source:'staff'}).status,'pending');
  assert.equal(new ServiceStore(file).list().find(r=>r.id===staffReservation.id).status,'confirmed');
  store.pickup.update({revision:3,paused:false});
  const dish=store.menu.list().find(i=>i.id==='appetizers-22');
  const soldOut=store.menu.update(dish.id,{revision:dish.revision,available:false});
  assert.equal(soldOut.available,false);
  assert.throws(()=>store.create(input),/sold out/);
  assert.equal(store.list().find(i=>i.id===r.id).items[0].price,400);
  assert.throws(()=>store.menu.update(dish.id,{revision:dish.revision,available:true}),/another tab/);
  const restarted=new ServiceStore(file);
  assert.equal(restarted.menu.list().find(i=>i.id===dish.id).available,false);
  restarted.menu.update(dish.id,{revision:soldOut.revision,available:true});
  assert.equal(restarted.create(input).subtotal,800);
  assert.throws(()=>restarted.menu.update(dish.id,{revision:2,available:'yes'}),/true or false/);
  console.log('PASS: validation, pickup-only intake, conflict protection, pickup lifecycle, durable restart, event log, reservation confirmation');
} finally { fs.rmSync(dir,{recursive:true,force:true}); }
