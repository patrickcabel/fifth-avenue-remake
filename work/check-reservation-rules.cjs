const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {ReservationRules}=require('../reservation-rules.cjs'),{ServiceStore}=require('../service-store.cjs');
const dir=fs.mkdtempSync(path.join(__dirname,'store-test-rules-'));
try{
  const rules=new ReservationRules(path.join(dir,'rules.json'));
  assert.equal(rules.get().totalTables,40);assert.equal(rules.get().walkInTables,10);
  assert.equal(rules.get().hours[1].open,'11:00');
  assert.equal(rules.get().hours[6].open,'12:00');
  assert.equal(rules.get().hours[0].close,'21:00');
  assert.equal(rules.check({date:'2099-01-05',time:'19:00',tableCount:1},[]).allowed,true);
  assert.equal(rules.check({date:'2099-01-05',time:'19:01',tableCount:1},[]).allowed,false);
  const legacyFile=path.join(dir,'legacy-rules.json');
  fs.writeFileSync(legacyFile,JSON.stringify({revision:3,totalTables:40,walkInTables:10,durationMinutes:120,noShowMinutes:15,hours:[{closed:true},null,null,null,null,null,null]}));
  const migrated=new ReservationRules(legacyFile);
  assert.equal(migrated.get().hours[0].closed,true);
  assert.equal(migrated.get().hours[1].open,'11:00');
  assert.equal(migrated.get().revision,4);
  assert.equal(new ReservationRules(legacyFile).get().revision,4);
  migrated.update({...migrated.get(),hours:Array(7).fill(null)});
  assert.equal(new ReservationRules(legacyFile).get().hours[1],null);
  const date='2099-01-05',candidate={date,time:'18:00',tableCount:1};
  const row={id:'a',type:'reservation',status:'confirmed',date,time:'17:00',durationMinutes:120,tableCount:30};
  assert.equal(rules.check(candidate,[row]).allowed,false);
  assert.equal(rules.check({...candidate,time:'19:00'},[row]).allowed,true);
  assert.equal(rules.check({...candidate,id:'a',tableCount:30},[row]).allowed,true);
  assert.equal(rules.check(candidate,[{...row,status:'pending'}]).allowed,true);
  assert.equal(rules.check(candidate,[{...row,status:'cancelled'}]).otherTablesAtPeak,0);
  assert.equal(rules.check(candidate,[{...row,status:'arrived'}]).allowed,false);
  const staggered=[{...row,tableCount:15,durationMinutes:60},{...row,id:'b',tableCount:15,time:'19:00',durationMinutes:60}];
  assert.equal(rules.check({...candidate,tableCount:15},staggered).allowed,true);
  const hours=Array.from({length:7},()=>({closed:false,open:'12:00',close:'22:00'}));
  rules.update({...rules.get(),hours});
  assert.equal(rules.check({...candidate,time:'20:00'},[]).allowed,true);
  assert.equal(rules.check({...candidate,time:'20:01'},[]).allowed,false);
  assert.equal(rules.check({...candidate,time:'11:00'},[]).allowed,false);
  assert.throws(()=>rules.update({...rules.get(),walkInTables:41}),/cannot exceed/);
  assert.throws(()=>rules.update({...rules.get(),revision:0}),/another tab/);
  assert.equal(new ReservationRules(path.join(dir,'rules.json')).get().hours[0].open,'12:00');
  const booking={type:'reservation',status:'confirmed',date:'2025-01-01',time:'12:00'};
  assert.equal(rules.expired(booking,Date.parse('2025-01-01T19:14:59Z')),false);
  assert.equal(rules.expired(booking,Date.parse('2025-01-01T19:15:00Z')),true);
  assert.equal(rules.expired({...booking,status:'arrived'},Date.parse('2025-01-01T20:00:00Z')),false);
  const store=new ServiceStore(path.join(dir,'requests.json'));
  const future=new Date(Date.now()+7*86400000).toISOString().slice(0,10);
  const input={type:'reservation',source:'staff',name:'Test Guest',phone:'4035550101',date:future,time:'18:00',guests:4,confirmed:true,tableCount:30};
  const full=store.create(input);
  assert.throws(()=>store.create({...input,tableCount:1}),/exceed/);
  const pending=store.create({...input,tableCount:1,confirmed:false});
  assert.throws(()=>store.update(pending.id,{action:'accept',revision:1}),/exceed/);
  store.update(full.id,{action:'cancel_reservation',revision:1,reason:'Test cancellation'});
  assert.equal(store.update(pending.id,{action:'accept',revision:1}).status,'confirmed');
  const records=store.list(),target=records.find(r=>r.id===pending.id);
  target.date='2025-01-01';target.time='12:00';store.commit(records);
  assert.equal(store.autoCancelNoShows(Date.parse('2025-01-01T19:15:00Z')),1);
  const cancelled=store.list().find(r=>r.id===pending.id);
  assert.equal(cancelled.status,'cancelled');assert.match(cancelled.cancellationReason,/15 minutes/);
  assert.equal(cancelled.events.at(-1).action,'auto_cancel_no_show');
  assert.equal(store.autoCancelNoShows(Date.parse('2025-01-01T20:00:00Z')),0);
  assert.equal(new ServiceStore(path.join(dir,'requests.json')).list().find(r=>r.id===pending.id).status,'cancelled');
  console.log('PASS: walk-in protection, overlap sweep, boundary turnover, hours, persistence, confirmation recheck, 15-minute cancellation, arrival exemption, idempotent sweep');
}finally{fs.rmSync(dir,{recursive:true,force:true});}
