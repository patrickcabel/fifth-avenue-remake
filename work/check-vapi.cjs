const assert=require('node:assert/strict'), fs=require('node:fs'),path=require('node:path');
const {ServiceStore}=require('../service-store.cjs');
const {handleTools,authorized,createWebhookServer,summarizeOrder,normalizePhone}=require('../vapi-webhook.cjs');
const dir=fs.mkdtempSync(path.join(__dirname,'store-test-vapi-'));
async function run() {
  const store=new ServiceStore(path.join(dir,'requests.json'));
  assert.equal(normalizePhone('+1 (403) 555-0123'),normalizePhone('403-555-0123'));
  assert.notEqual(normalizePhone('+44 20 7946 0018'),normalizePhone('403-555-0123'));
  assert.equal(normalizePhone('not-a-phone'),null);
  let changes=0;
  const payload=(name,args={},callId='test-call-1',toolId='tool-1')=>({message:{type:'tool-calls',call:{id:callId},toolCallList:[{id:toolId,function:{name,arguments:args}}]}});
  const invoke=(name,args,callId,toolId)=>handleTools(store,payload(name,args,callId,toolId),()=>changes++).results[0];
  const args={name:'Test Guest',phone:'555-0101',items:[{menuId:'appetizers-22',qty:2}],customerConfirmed:true};
  assert.ok(invoke('submit_pickup_order',{...args,customerConfirmed:false}).error);
  assert.equal(store.list().length,0);
  const order=JSON.parse(invoke('submit_pickup_order',args).result);
  assert.equal(order.status,'pending');assert.equal(order.subtotalCents,800);
  assert.equal(order.pickupTimeLocal,null);
  assert.match(order.customerMessage,/waiting for restaurant approval/);
  assert.equal(store.list()[0].source,'vapi');
  assert.equal(JSON.parse(invoke('submit_pickup_order',args,'test-call-1','different-tool-id').result).orderId,order.orderId);
  assert.equal(changes,1);assert.equal(store.list().length,1);
  assert.ok(invoke('submit_pickup_order',{...args,name:'Different guest'}).error);
  assert.ok(invoke('get_current_order_status',{},'different-call').error);
  assert.ok(invoke('accept_order',{}).error);
  store.update(order.orderId,{revision:1,action:'accept'});
  const acceptedStatus=JSON.parse(invoke('get_current_order_status',{}).result);
  assert.equal(acceptedStatus.status,'accepted');
  assert.ok(acceptedStatus.pickupTimeLocal);
  assert.match(acceptedStatus.customerMessage,/estimated pickup time/);
  assert.equal(order.orderReference,order.orderId);
  const callback=JSON.parse(invoke('get_current_order_status',{name:'  TEST   GUEST ',phone:'(555) 0101'},'new-callback-call').result);
  assert.equal(callback.orderId,order.orderId);
  assert.equal(callback.status,'accepted');
  assert.equal(callback.pickupTimeLocal,acceptedStatus.pickupTimeLocal);
  assert.ok(!('phone' in callback));
  assert.ok(invoke('get_current_order_status',{name:'Test Guest',phone:'555-9999'},'new-callback-call').error);
  assert.ok(invoke('get_current_order_status',{name:'Test Guest'},'new-callback-call').error);
  assert.ok(invoke('get_current_order_status',{phone:'555-0101'},'new-callback-call').error);
  assert.ok(invoke('get_current_order_status',{name:'Wrong Guest',phone:'555-0101'},'new-callback-call').error);
  const winterTime=Date.parse('2025-01-01T20:25:00Z');
  const winter=summarizeOrder({status:'accepted',readyAt:winterTime,minutes:25},winterTime-10*60000);
  assert.match(winter.pickupTimeLocal,/1:25/);
  assert.match(winter.pickupTimeLocal,/MST/);
  assert.equal(winter.estimatedMinutesRemaining,10);
  const summer=summarizeOrder({status:'accepted',readyAt:Date.parse('2025-07-01T20:25:00Z'),minutes:25});
  assert.match(summer.pickupTimeLocal,/2:25/);
  assert.match(summer.pickupTimeLocal,/MDT/);
  assert.match(summarizeOrder({status:'accepted',readyAt:winterTime,minutes:25},winterTime+60000).customerMessage,/not yet been marked ready/);
  assert.match(summarizeOrder({status:'ready',readyAt:winterTime}).customerMessage,/ready for pickup/);
  assert.match(summarizeOrder({status:'declined',reason:'Kitchen closed'}).customerMessage,/Kitchen closed/);
  store.pickup.update({revision:0,paused:true});
  const pausedStatus=JSON.parse(invoke('get_pickup_status',{}).result);
  assert.equal(pausedStatus.paused,true);
  assert.equal(pausedStatus.acceptingOrders,false);
  assert.equal(pausedStatus.status,'paused');
  assert.equal(JSON.parse(invoke('get_current_order_status',{name:'Test Guest',phone:'555-0101'},'callback-while-paused').result).status,'accepted');
  assert.match(pausedStatus.customerMessage,/cannot take a new pickup order/);
  assert.ok(invoke('submit_pickup_order',args,'paused-call').error);
  assert.equal(JSON.parse(invoke('submit_pickup_order',args).result).status,'accepted');
  store.pickup.update({revision:1,paused:false});
  const openStatus=JSON.parse(invoke('get_pickup_status',{}).result);
  assert.equal(openStatus.acceptingOrders,true);
  assert.equal(openStatus.status,'open');
  store.menu.update('appetizers-22',{revision:0,available:false});
  assert.ok(invoke('submit_pickup_order',args,'sold-out-call').error);
  assert.equal(JSON.parse(invoke('search_pickup_menu',{query:'Miso Soup'}).result).items.length,0);
  const batch=payload('get_pickup_status');
  batch.message.toolCallList.push({id:'bad',function:{name:'unknown',arguments:{}}});
  const results=handleTools(store,batch).results;
  assert.equal(results.length,2);assert.equal(typeof results[0].result,'string');assert.equal(typeof results[1].error,'string');
  const restarted=new ServiceStore(path.join(dir,'requests.json'));
  const lookupAfterRestart=handleTools(restarted,payload('get_current_order_status',{name:'Test Guest',phone:'555-0101'},'callback-after-restart')).results[0];
  assert.equal(JSON.parse(lookupAfterRestart.result).orderId,order.orderId);
  const restartedOrder=restarted.list().find(r=>r.id===order.orderId);
  const readyOrder=restarted.update(order.orderId,{revision:restartedOrder.revision,action:'ready'});
  const callbackPayload=payload('get_current_order_status',{name:'Test Guest',phone:'555-0101'},'callback-ready');
  assert.equal(JSON.parse(handleTools(restarted,callbackPayload).results[0].result).status,'ready');
  restarted.update(order.orderId,{revision:readyOrder.revision,action:'complete'});
  assert.equal(JSON.parse(handleTools(restarted,callbackPayload).results[0].result).status,'completed');
  const originalInStore=store.list().find(r=>r.id===order.orderId);
  store.update(order.orderId,{revision:originalInStore.revision,action:'ready'});
  const second=store.create({...args,type:'order',mode:'Pickup',items:[{menuId:'sushi-rolls-1',qty:1}]});
  const ambiguous=JSON.parse(invoke('get_current_order_status',{name:'Test Guest',phone:'555-0101'},'multiple-orders').result);
  assert.equal(ambiguous.needsSelection,true);
  assert.equal(ambiguous.found,true);
  assert.equal(ambiguous.status,'selection_required');
  assert.equal(ambiguous.lookupOutcome,'multiple_orders_found');
  assert.equal(ambiguous.matchCount,2);
  assert.equal(ambiguous.candidates.length,2);
  assert.ok(ambiguous.candidates[0].itemSummary);
  assert.ok(!('status' in ambiguous.candidates[0]));
  const selected=JSON.parse(invoke('get_current_order_status',{name:'Test Guest',phone:'555-0101',orderId:second.id},'multiple-orders').result);
  assert.equal(selected.orderId,second.id);
  assert.equal(selected.status,'pending');
  const readySelection=JSON.parse(invoke('get_current_order_status',{name:'Test Guest',phone:'555-0101',orderId:order.orderId},'multiple-orders').result);
  assert.equal(readySelection.status,'ready');
  assert.equal(readySelection.found,true);
  assert.equal(readySelection.needsSelection,false);
  assert.equal(readySelection.lookupOutcome,'order_found');
  assert.match(readySelection.customerMessage,/ready for pickup/);
  const firstNameReady=JSON.parse(invoke('get_current_order_status',{name:'Test',phone:'555-0101',orderId:' '+order.orderId.toLowerCase()+' '},'first-name-ready').result);
  assert.equal(firstNameReady.status,'ready');
  const blankSelection=JSON.parse(invoke('get_current_order_status',{name:'Test Guest',phone:'555-0101',orderId:''},'blank-selection').result);
  assert.equal(blankSelection.needsSelection,true);
  const nullSelection=JSON.parse(invoke('get_current_order_status',{name:'Test Guest',phone:'555-0101',orderId:null},'null-selection').result);
  assert.equal(nullSelection.needsSelection,true);
  assert.equal(JSON.parse(invoke('get_current_order_status',{name:'',phone:'',orderId:''}).result).status,'ready');
  const audit=[];
  handleTools(store,payload('get_current_order_status',{name:'Test Guest',phone:'555-0101',orderId:order.orderId},'audit-call'),()=>{},entry=>audit.push(entry));
  assert.equal(audit[0].status,'ready');
  assert.ok(!JSON.stringify(audit).includes('Test Guest'));
  assert.ok(!JSON.stringify(audit).includes('555-0101'));
  store.create({type:'order',mode:'Pickup',name:'Test Other',phone:'555-0101',items:[{menuId:'sushi-rolls-1',qty:1}]});
  assert.match(invoke('get_current_order_status',{name:'Test',phone:'555-0101'},'shared-first-name').error,/full name/);
  assert.ok(invoke('get_current_order_status',{name:'Wrong Guest',phone:'555-0101',orderId:second.id},'multiple-orders').error);
  assert.equal(JSON.parse(handleTools(restarted,payload('submit_pickup_order',args)).results[0].result).orderId,order.orderId);
  assert.ok(!authorized('Bearer anything',''));
  assert.ok(!authorized('Bearer incorrect','a'.repeat(64)));
  assert.ok(authorized('Bearer '+'a'.repeat(64),'a'.repeat(64)));
  const server=createWebhookServer(store,()=>{},'a'.repeat(64));
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  try {
    const base='http://127.0.0.1:'+server.address().port;
    assert.equal((await fetch(base+'/api/requests')).status,404);
    assert.equal((await fetch(base+'/vapi/tools',{method:'POST'})).status,401);
    assert.equal((await fetch(base+'/vapi/tools',{method:'POST',headers:{Authorization:'Bearer '+'a'.repeat(64),'Content-Type':'application/json'},body:'invalid'})).status,400);
    const response=await fetch(base+'/vapi/tools',{method:'POST',headers:{Authorization:'Bearer '+'a'.repeat(64),'Content-Type':'application/json'},body:JSON.stringify(payload('get_pickup_status'))});
    assert.equal(response.status,200);assert.equal((await response.json()).results[0].toolCallId,'tool-1');
    console.log('PASS: Vapi auth, isolated HTTP listener, result format, read-back guard, call isolation, deduplication/restart, menu availability, pickup pause, staff decisions');
  } finally {await new Promise(resolve=>server.close(resolve));}
}
run().catch(e=>{console.error(e);process.exitCode=1;}).finally(()=>fs.rmSync(dir,{recursive:true,force:true}));
