const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {ServiceStore}=require('../service-store.cjs');
const {handleTools}=require('../vapi-webhook.cjs');
const dir=fs.mkdtempSync(path.join(__dirname,'store-test-reservation-'));
try {
  let store=new ServiceStore(path.join(dir,'requests.json')),changes=0;
  const call=(name,args={},id='booking-call')=>handleTools(store,{message:{type:'tool-calls',call:{id},toolCallList:[{id:'tool',function:{name,arguments:args}}]}},()=>changes++).results[0];
  const context=JSON.parse(call('get_reservation_context').result);
  assert.match(context.today,/^\d{4}-\d{2}-\d{2}$/);
  assert.equal(context.availabilityChecked,false);
  const date=new Date(Date.now()+7*86400000).toISOString().slice(0,10);
  const args={name:'Test Guest',phone:'403-555-0101',date,time:'19:00',guests:4,note:'Window preference',customerConfirmed:true};
  assert.ok(call('submit_reservation_request',{...args,customerConfirmed:false}).error);
  const request=JSON.parse(call('submit_reservation_request',args).result);
  assert.equal(request.status,'pending');
  assert.equal(store.list()[0].source,'vapi');
  assert.equal(JSON.parse(call('submit_reservation_request',args).result).reservationId,request.reservationId);
  assert.equal(changes,1);
  assert.ok(call('submit_reservation_request',{...args,guests:5}).error);
  assert.ok(call('submit_reservation_request',{...args,date:'2000-01-01'},'past-call').error);
  assert.ok(call('submit_reservation_request',{...args,time:'29:00'},'bad-time-call').error);
  store.update(request.reservationId,{revision:1,action:'accept'});
  assert.equal(JSON.parse(call('get_reservation_status').result).status,'confirmed');
  assert.ok(call('get_reservation_status',{},'unrelated-call').error);
  const lookup={name:'test',phone:'+1 (403) 555-0101'};
  assert.equal(JSON.parse(call('get_reservation_status',lookup,'callback').result).status,'confirmed');
  assert.ok(call('get_reservation_status',{...lookup,phone:'4035559999'},'callback').error);
  const second=JSON.parse(call('submit_reservation_request',{...args,time:'18:00'},'another-booking-call').result);
  const multiple=JSON.parse(call('get_reservation_status',lookup,'callback').result);
  assert.equal(multiple.found,true);assert.equal(multiple.needsSelection,true);assert.equal(multiple.candidates.length,2);
  store.update(second.reservationId,{revision:1,action:'decline',reason:'Fully booked'});
  const declined=JSON.parse(call('get_reservation_status',{...lookup,reservationId:second.reservationId},'callback').result);
  assert.equal(declined.status,'declined');assert.match(declined.customerMessage,/Fully booked/);
  store.pickup.update({revision:0,paused:true});
  const third=JSON.parse(call('submit_reservation_request',{...args,time:'17:00'},'paused-pickup-call').result);
  assert.equal(third.status,'pending');
  assert.ok(call('get_current_order_status',{},'booking-call').error);
  store=new ServiceStore(path.join(dir,'requests.json'));
  assert.equal(JSON.parse(call('get_reservation_status',{...lookup,reservationId:request.reservationId},'restart-callback').result).status,'confirmed');
  const slot=JSON.parse(call('check_reservation_slot',{date,time:'19:00',guests:4},'slot-check').result);
  assert.equal(slot.checked,true);assert.equal(slot.allowed,true);assert.equal(slot.reservableTables,30);
  store.reservationRules.update({...store.reservationRules.get(),totalTables:1,walkInTables:0});
  const fullSlot=JSON.parse(call('check_reservation_slot',{date,time:'19:00',guests:4},'full-slot-check').result);
  assert.equal(fullSlot.allowed,false);
  assert.ok(call('submit_reservation_request',args,'full-slot-submit').error);
  store.reservationRules.update({...store.reservationRules.get(),hours:Array.from({length:7},()=>({closed:true}))});
  assert.equal(JSON.parse(call('check_reservation_slot',{date,time:'21:00',guests:4},'closed-slot-check').result).allowed,false);
  console.log('PASS: Vapi reservation context, approval guard, idempotency, date validation, confirmation/decline, callback verification, selection, restart, independence from pickup pause');
}finally{fs.rmSync(dir,{recursive:true,force:true});}
